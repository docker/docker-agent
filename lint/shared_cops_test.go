func TestSharedCopsPartialTypesAndInactiveFiles(t *testing.T) {
	dir := t.TempDir()
	t.Chdir(dir)
	require.NoError(t, os.WriteFile("go.mod", []byte("module example.test\n\ngo 1.27\n"), 0o600))
	const src = `package p
import command "os/exec"
func NewCommand(cmd *command.Cmd) *command.Cmd {
	_ = cmd.Run()
	return command.Command("echo")
}
func clone(s []int) []int { return append([]int(nil), s...) }
`
	files := map[string]string{
		"healthy/sample.go":            src,
		"tests/sample.go":              "package p\n",
		"tests/sample_test.go":         src + "\nvar _ = missing\n",
		"external/sample.go":           "package p\n",
		"external/sample_test.go":      strings.Replace(src, "package p", "package p_test", 1) + "\nvar _ = missing\n",
		"testonly/sample_test.go":      src + "\nvar _ = missing\n",
		"platform/sample.go":           "package p\n",
		"platform/sample_linux.go":     "//go:build linux\n\n" + src,
		"platform/sample_windows.go":   "//go:build windows\n\n" + src,
		"platform/sample_darwin.go":    "//go:build darwin\n\n" + src,
		"inactiveonly/sample.go":       "//go:build lint_fixture_disabled\n\n" + src,
		"split/sample.go":              "package p\nimport \"os/exec\"\ntype Command = exec.Cmd\n",
		"split/sample_feature.go":      "//go:build lint_fixture_disabled\n\npackage p\nfunc NewCommand(cmd *Command) *Command { _ = cmd.Run(); return cmd }\n",
		"tagged/sample.go":             "package p\n",
		"tagged/sample_feature.go":     "//go:build lint_fixture_disabled\n\n" + src,
		"taggedtests/sample.go":        "package p\n",
		"taggedtests/sample_test.go":   "//go:build lint_fixture_disabled\n\n" + src,
		"suppressed/sample.go":         "package p\n",
		"suppressed/sample_feature.go": "//go:build lint_fixture_disabled\n\n//rubocop:disable-file Lint/ConstructorCommandExec\n" + src,
	}
	for name, content := range files {
		require.NoError(t, os.MkdirAll(filepath.Dir(name), 0o700))
		require.NoError(t, os.WriteFile(name, []byte(content), 0o600))
	}
	for _, name := range []string{"ConstructorCommandExec", "SlicesClone"} {
		t.Run(name, func(t *testing.T) {
			var output bytes.Buffer
			r := runner.New(nil, config.DefaultConfig(), &output)
			if name == "ConstructorCommandExec" {
				r = runner.New([]cop.Cop{registeredSharedCop(t, cops, "Lint/"+name)}, config.DefaultConfig(), &output)
			} else {
				r.WithProgramCops([]prog.Cop{registeredSharedCop(t, programCops, "Lint/"+name)})
			}
			r.Reporter = runner.NewJSONReporter(&output)
			_, err := r.Run([]string{"."})
			require.NoError(t, err)
			var report struct {
				Offenses []struct{ Cop, File string }
			}
			require.NoError(t, json.Unmarshal(output.Bytes(), &report))
			got := make(map[string]int)
			for _, offense := range report.Offenses {
				assert.Equal(t, "Lint/"+name, offense.Cop)
				file := offense.File
				if filepath.IsAbs(file) {
					file, err = filepath.Rel(dir, file)
					require.NoError(t, err)
				}
				got[strings.TrimPrefix(filepath.ToSlash(file), "./")]++
			}
			want := make(map[string]int)
			for _, file := range []string{"healthy/sample.go", "tests/sample_test.go", "external/sample_test.go", "testonly/sample_test.go"} {
				if name == "ConstructorCommandExec" {
					want[file] = 2
				} else {
					want[file] = 1
				}
			}
			if name == "ConstructorCommandExec" {
				want["split/sample_feature.go"] = 1
				for _, file := range []string{"inactiveonly/sample.go", "platform/sample_linux.go", "platform/sample_windows.go", "platform/sample_darwin.go", "tagged/sample_feature.go", "taggedtests/sample_test.go"} {
					want[file] = 2
				}
			} else {
				want["platform/sample_"+goruntime.GOOS+".go"] = 1
			}
			assert.Equal(t, want, got, output.String())
		})
	}
}

func registeredSharedCop[T interface{ Name() string }](t *testing.T, registered []T, name string) T {
	t.Helper()
	i := slices.IndexFunc(registered, func(c T) bool { return c.Name() == name })
	require.NotEqual(t, -1, i, "missing registered cop %s", name)
	return registered[i]
}
