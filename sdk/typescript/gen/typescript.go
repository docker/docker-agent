package main

import (
	"cmp"
	"errors"
	"fmt"
	"reflect"
	"regexp"
	"slices"
	"strconv"
	"strings"

	"github.com/google/jsonschema-go/jsonschema"
)

const header = "// Code generated by go run ./sdk/typescript/gen; DO NOT EDIT.\n"

// emitTypeScript renders the types of each module to <module>.ts.
func emitTypeScript(defs []*def) (map[string]string, error) {
	moduleOf := map[string]string{}
	byModule := map[string][]*def{}
	for _, d := range defs {
		moduleOf[d.name] = d.module
		byModule[d.module] = append(byModule[d.module], d)
	}

	files := map[string]string{}
	for _, module := range sortedKeys(byModule) {
		content, err := emitModule(module, byModule[module], moduleOf)
		if err != nil {
			return nil, err
		}
		files[module+".ts"] = content
	}
	return files, nil
}

// emitIndex re-exports every generated file.
func emitIndex(files map[string]string) string {
	var index strings.Builder
	index.WriteString(header)
	for _, name := range sortedKeys(files) {
		fmt.Fprintf(&index, "export * from './%s.js';\n", strings.TrimSuffix(name, ".ts"))
	}
	return index.String()
}

func emitModule(module string, defs []*def, moduleOf map[string]string) (string, error) {
	e := &tsEmitter{imports: map[string]map[string]bool{}, module: module, moduleOf: moduleOf}
	slices.SortFunc(defs, func(a, b *def) int { return cmp.Compare(a.name, b.name) })

	var body strings.Builder
	for _, d := range defs {
		decl, err := e.declaration(d)
		if err != nil {
			return "", fmt.Errorf("%s: %w", d.name, err)
		}
		body.WriteString("\n")
		body.WriteString(decl)
	}

	var out strings.Builder
	out.WriteString(header)
	if len(e.imports) > 0 {
		out.WriteString("\n")
	}
	for _, from := range sortedKeys(e.imports) {
		fmt.Fprintf(&out, "import type { %s } from './%s.js';\n", strings.Join(sortedKeys(e.imports[from]), ", "), from)
	}
	out.WriteString(body.String())
	return out.String(), nil
}

type tsEmitter struct {
	module   string
	moduleOf map[string]string
	imports  map[string]map[string]bool
}

func (e *tsEmitter) declaration(d *def) (string, error) {
	s := d.schema
	doc := jsDoc("", joinNonEmpty("\n\n", s.Description, prefixed("Go: ", s.Comment)))

	if s.Type == "object" && len(s.Properties) > 0 {
		body, err := e.objectBody(s, "  ")
		if err != nil {
			return "", err
		}
		return fmt.Sprintf("%sexport interface %s {\n%s}\n", doc, d.name, body), nil
	}

	t, err := e.typeOf(s)
	if err != nil {
		return "", err
	}
	members := len(s.OneOf) + len(s.AnyOf) + len(s.Enum)
	if line := fmt.Sprintf("export type %s = %s;", d.name, t); len(line) <= 100 || members < 2 {
		return doc + line + "\n", nil
	}
	return fmt.Sprintf("%sexport type %s =\n  | %s;\n", doc, d.name, strings.ReplaceAll(t, " | ", "\n  | ")), nil
}

func (e *tsEmitter) objectBody(s *jsonschema.Schema, indent string) (string, error) {
	var b strings.Builder
	for _, name := range propertyNames(s) {
		p := s.Properties[name]
		t, err := e.typeOf(p)
		if err != nil {
			return "", fmt.Errorf("property %s: %w", name, err)
		}
		optional := "?"
		if slices.Contains(s.Required, name) {
			optional = ""
		}
		b.WriteString(jsDoc(indent, p.Description))
		fmt.Fprintf(&b, "%s%s%s: %s;\n", indent, propertyKey(name), optional, t)
	}
	if extra := s.AdditionalProperties; extra != nil && !isFalse(extra) {
		t, err := e.typeOf(extra)
		if err != nil {
			return "", err
		}
		fmt.Fprintf(&b, "%s[key: string]: %s;\n", indent, t)
	}
	return b.String(), nil
}

func (e *tsEmitter) typeOf(s *jsonschema.Schema) (string, error) {
	if err := checkSupported(s); err != nil {
		return "", err
	}
	switch {
	case s.Ref != "":
		return e.ref(s.Ref)
	case s.Const != nil:
		return literal(*s.Const)
	case len(s.Enum) > 0:
		var members []string
		for _, v := range s.Enum {
			l, err := literal(v)
			if err != nil {
				return "", err
			}
			members = append(members, l)
		}
		return union(members), nil
	case len(s.AnyOf) > 0 || len(s.OneOf) > 0:
		var members []string
		for _, m := range slices.Concat(s.AnyOf, s.OneOf) {
			t, err := e.typeOf(m)
			if err != nil {
				return "", err
			}
			members = append(members, t)
		}
		return union(members), nil
	case len(s.Types) > 0:
		var members []string
		for _, typ := range s.Types {
			single := *s
			single.Types, single.Type = nil, typ
			t, err := e.typeOf(&single)
			if err != nil {
				return "", err
			}
			members = append(members, t)
		}
		return union(members), nil
	}

	switch s.Type {
	case "string":
		return "string", nil
	case "integer", "number":
		return "number", nil
	case "boolean":
		return "boolean", nil
	case "null":
		return "null", nil
	case "array":
		items := "unknown"
		if s.Items != nil {
			t, err := e.typeOf(s.Items)
			if err != nil {
				return "", err
			}
			items = t
		}
		if strings.Contains(items, " ") {
			items = "(" + items + ")"
		}
		return items + "[]", nil
	case "object":
		return e.objectType(s)
	case "":
		return "unknown", nil
	default:
		return "", fmt.Errorf("unsupported type %q", s.Type)
	}
}

func (e *tsEmitter) objectType(s *jsonschema.Schema) (string, error) {
	if len(s.Properties) > 0 {
		body, err := e.objectBody(stripDocs(s), "")
		if err != nil {
			return "", err
		}
		return "{ " + strings.TrimSuffix(strings.ReplaceAll(strings.TrimSuffix(body, "\n"), "\n", " "), ";") + " }", nil
	}
	switch extra := s.AdditionalProperties; {
	case extra == nil && s.Properties != nil:
		// A struct without fields.
		return "Record<string, never>", nil
	case extra == nil:
		return "Record<string, unknown>", nil
	case isFalse(extra):
		return "Record<string, never>", nil
	default:
		t, err := e.typeOf(extra)
		if err != nil {
			return "", err
		}
		return "Record<string, " + t + ">", nil
	}
}

func (e *tsEmitter) ref(ref string) (string, error) {
	name, ok := strings.CutPrefix(ref, "#/$defs/")
	if !ok {
		return "", fmt.Errorf("unsupported $ref %q", ref)
	}
	module, ok := e.moduleOf[name]
	if !ok {
		return "", fmt.Errorf("$ref to unknown def %q", name)
	}
	if module != e.module {
		if e.imports[module] == nil {
			e.imports[module] = map[string]bool{}
		}
		e.imports[module][name] = true
	}
	return name, nil
}

// checkSupported rejects keywords the emitters would otherwise silently drop.
func checkSupported(s *jsonschema.Schema) error {
	switch {
	case len(s.AllOf) > 0, s.Not != nil, s.If != nil, len(s.PrefixItems) > 0, len(s.PatternProperties) > 0, len(s.DependentSchemas) > 0:
		return fmt.Errorf("%w: %s", errUnsupportedSchema, s)
	}
	return nil
}

var errUnsupportedSchema = errors.New("unsupported schema keyword")

func stripDocs(s *jsonschema.Schema) *jsonschema.Schema {
	c := *s
	c.Properties = map[string]*jsonschema.Schema{}
	for k, p := range s.Properties {
		pc := *p
		pc.Description = ""
		c.Properties[k] = &pc
	}
	return &c
}

func propertyNames(s *jsonschema.Schema) []string {
	if len(s.PropertyOrder) == len(s.Properties) {
		return s.PropertyOrder
	}
	return sortedKeys(s.Properties)
}

func isFalse(s *jsonschema.Schema) bool {
	return s.Not != nil && reflect.ValueOf(*s.Not).IsZero()
}

func union(members []string) string {
	var unique []string
	for _, m := range members {
		if !slices.Contains(unique, m) {
			unique = append(unique, m)
		}
	}
	return strings.Join(unique, " | ")
}

func literal(v any) (string, error) {
	switch v := v.(type) {
	case string:
		return "'" + strings.NewReplacer(`\`, `\\`, `'`, `\'`, "\n", `\n`).Replace(v) + "'", nil
	case bool:
		return strconv.FormatBool(v), nil
	case int, int64, float64:
		return fmt.Sprint(v), nil
	default:
		return "", fmt.Errorf("unsupported literal %#v", v)
	}
}

var identifier = regexp.MustCompile(`^[A-Za-z_$][A-Za-z0-9_$]*$`)

func propertyKey(name string) string {
	if identifier.MatchString(name) {
		return name
	}
	l, _ := literal(name)
	return l
}

func jsDoc(indent, text string) string {
	text = strings.TrimSpace(strings.ReplaceAll(text, "*/", `*\/`))
	if text == "" {
		return ""
	}
	lines := strings.Split(text, "\n")
	if len(lines) == 1 {
		return indent + "/** " + lines[0] + " */\n"
	}
	var b strings.Builder
	b.WriteString(indent + "/**\n")
	for _, l := range lines {
		b.WriteString(strings.TrimRight(indent+" * "+l, " ") + "\n")
	}
	b.WriteString(indent + " */\n")
	return b.String()
}

func prefixed(prefix, s string) string {
	if s == "" {
		return ""
	}
	return prefix + s
}

func sortedKeys[V any](m map[string]V) []string {
	keys := make([]string, 0, len(m))
	for k := range m {
		keys = append(keys, k)
	}
	slices.Sort(keys)
	return keys
}
