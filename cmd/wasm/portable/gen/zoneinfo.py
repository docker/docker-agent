"""Generate zoneinfo.mjs from the active Go toolchain's IANA database."""

import base64
import json
import re
import struct
import subprocess
import zipfile
from pathlib import Path


def tzif(data):
    # Skip the TZif v1 block. Go ships slim v2/v3 files with 64-bit transitions.
    def counts(at):
        assert data[at:at + 5] in (b'TZif2', b'TZif3')
        return struct.unpack_from('>6I', data, at + 20)

    utc, std, leaps, count, types, chars = counts(0)
    at = 44 + utc + std + leaps * 8 + count * 5 + types * 6 + chars
    utc, std, leaps, count, types, chars = counts(at)
    at += 44
    times = struct.unpack_from(f'>{count}q', data, at)
    at += count * 8
    indices = data[at:at + count]
    at += count
    records = list(struct.iter_unpack('>iBB', data[at:at + 6 * types]))
    at += 6 * types
    names = data[at:at + chars]
    states = [(names[i:names.index(0, i)].decode(), offset) for offset, _, i in records]
    # time.Location.lookupFirstZone: type zero unless referenced, then a preceding standard type.
    first = 0
    if first in indices:
        standard = [i for i, (_, dst, _) in enumerate(records) if not dst]
        first = next(iter(standard), 0)
        if records[indices[0]][1]:
            first = max((i for i in standard if i < indices[0]), default=first)
    tail = data[at + chars + utc + std + leaps * 12:].strip(b'\n').decode()
    return states[first], zip(times, (states[i] for i in indices)), tail


def seconds(s):
    fields = [int(n) for n in s.lstrip('+-').split(':')]
    return (-1 if s.startswith('-') else 1) * sum(n * 60 ** (2 - i) for i, n in enumerate(fields))


def footer(s, state):
    name = r'(<[^>]+>|[A-Za-z]+)'
    offset = r'([+-]?\d+(?::\d+){0,2})'
    names, *rules = s.split(',')
    std, off, dst, alt = re.fullmatch(name + offset + '(?:' + name + offset + '?)?', names).groups()
    east = -seconds(off)
    result = [state((std.strip('<>'), east))]
    if dst:
        result.append(state((dst.strip('<>'), -seconds(alt) if alt else east + 3600)))
        assert len(rules) == 2
        for rule in rules:
            date, _, hour = rule.partition('/')
            m, w, d = re.fullmatch(r'M(\d+)\.(\d+)\.(\d+)', date).groups()
            result.append([int(m), int(w), int(d), seconds(hour or '2')])
    return result


def index(table, value):
    return table.setdefault(value, len(table))


def generate():
    root = Path(subprocess.check_output(['go', 'env', 'GOROOT'], text=True).strip())
    aliases = {}
    with zipfile.ZipFile(root / 'lib/time/zoneinfo.zip') as z:
        for name in sorted(z.namelist()):
            aliases.setdefault(z.read(name), []).append(name)

    states, steps, rules, zones = {}, {}, {}, []
    for data, names in aliases.items():
        initial, transitions, tail = tzif(data)
        first = index(states, initial)
        # Each distinct (interval, state) pair gets a shared 16-bit index.
        packed = bytearray()
        prev = 0
        for t, st in transitions:
            step = index(steps, (t - prev, index(states, st)))
            packed.extend(struct.pack('>H', step))
            prev = t
        rule = footer(tail, lambda st: index(states, st))
        zones.append([' '.join(names), first, index(rules, compact(rule)), base64.b64encode(packed).decode()])
    return '// Generated by gen/zoneinfo.py from Go lib/time/zoneinfo.zip. Do not edit.\n' + ''.join(
        f'export const {name} = {text};\n' for name, text in [
            ('states', compact(list(states))), ('steps', compact(list(steps))),
            ('rules', '[' + ','.join(rules) + ']'), ('zones', '[\n' + ',\n'.join(map(compact, zones)) + '\n]')])


def compact(value):
    return json.dumps(value, separators=(',', ':'))


if __name__ == '__main__':
    (Path(__file__).resolve().parents[1] / 'zoneinfo.mjs').write_text(generate())
