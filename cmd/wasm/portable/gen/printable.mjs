// strconv.IsPrint: space plus Unicode letters, marks, numbers, punctuation and symbols.
import { execFileSync } from 'node:child_process';
import { readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';

const root = execFileSync('go', ['env', 'GOROOT'], { encoding: 'utf8' }).trim();
const version = readFileSync(join(root, 'src/unicode/tables.go'), 'utf8').match(/const Version = "([\d.]+)"/)[1];
if (version.replace(/(?:\.0)+$/, '') !== process.versions.unicode.replace(/(?:\.0)+$/, '')) throw new Error(`use Node with Unicode ${version}`);
const boundaries = [];
let previous = false;
for (let n = 0; n <= 0x10ffff; n++) {
  const printable = /[\p{L}\p{M}\p{N}\p{P}\p{S} ]/u.test(String.fromCodePoint(n));
  if (printable !== previous) boundaries.push(n);
  previous = printable;
}
const rows = [];
while (boundaries.length) rows.push('    ' + boundaries.splice(0, 12).map(n => `0x${n.toString(16)}`).join(', ') + ',');
writeFileSync(new URL('../src/printable.in', import.meta.url), `// Generated by gen/printable.mjs (Unicode ${version}).\n&[\n${rows.join('\n')}\n]\n`);
